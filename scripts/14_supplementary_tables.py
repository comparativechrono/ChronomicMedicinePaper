#!/usr/bin/env python3
"""Write Supplementary Tables S1-S6 (xlsx) to results/supplementary/ with a Key sheet each."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from chronomic.common import INTERIM, ROOT, TABLES  # noqa: E402

OUT = ROOT / "results" / "supplementary"
OUT.mkdir(parents=True, exist_ok=True)
TITLE = ("Towards chronomic medicine: Mendelian disease genes and rare-variant convergence at chronotype loci "
         "(Malik & Hearn)")
F = Font(name="Arial", size=10)
FB = Font(name="Arial", size=10, bold=True)
FILL = PatternFill("solid", fgColor="E8EEF6")


def write(fname: str, label: str, sheets: list[tuple[str, pd.DataFrame, str]], notes: list[str]):
    wb = Workbook()
    ks = wb.active
    ks.title = "Key"
    ks["A1"] = TITLE
    ks["A1"].font = FB
    ks["A2"] = label
    ks["A2"].font = FB
    ks["A4"], ks["B4"] = "Sheet", "Contents"
    ks["A4"].font = ks["B4"].font = FB
    r = 5
    for name, _, desc in sheets:
        ks.cell(r, 1, name).font = F
        c = ks.cell(r, 2, desc)
        c.font = F
        c.alignment = Alignment(wrap_text=True, vertical="top")
        r += 1
    r += 1
    for n in notes:
        c = ks.cell(r, 1, n)
        c.font = F
        r += 1
    ks.column_dimensions["A"].width = 28
    ks.column_dimensions["B"].width = 120
    for name, df, _ in sheets:
        ws = wb.create_sheet(name[:31])
        df = df.copy()
        for j, col in enumerate(df.columns, 1):
            c = ws.cell(1, j, str(col))
            c.font = FB
            c.fill = FILL
            c.alignment = Alignment(wrap_text=True, vertical="top")
        for i, row in enumerate(df.itertuples(index=False), 2):
            for j, v in enumerate(row, 1):
                if isinstance(v, float) and pd.isna(v):
                    v = None
                elif hasattr(v, "item"):
                    v = v.item()
                ws.cell(i, j, v).font = F
        for j, col in enumerate(df.columns, 1):
            width = max([len(str(col))] + [len(str(x)) for x in df[col].head(200).tolist()])
            ws.column_dimensions[get_column_letter(j)].width = min(max(10, width + 2), 60)
        ws.freeze_panes = "A2"
        ws.auto_filter.ref = ws.dimensions
    wb.save(OUT / fname)


common_note = ["All coordinates are GRCh37 unless stated. Gene identifiers are Ensembl gene IDs (GENCODE v48).",
               "Generated by the scripts in https://github.com/comparativechrono/ChronomicMedicinePaper "
               "(see data/manifest.tsv for input versions, download dates and checksums)."]

# ---------------------------------------------------------------- S1 loci
leads = pd.read_csv(INTERIM / "loci" / "leads.tsv", sep="\t")
reg_genes = (pd.read_csv(INTERIM / "loci" / "locus_genes.tsv", sep="\t", dtype={"r2_level": str})
             .query("r2_level == '60'").groupby("locus_no").symbol.apply(lambda s: ";".join(s)))
ot = pd.read_csv(TABLES / "locus_opentargets.tsv", sep="\t")
s1 = leads[["locus_no", "lead_rsid", "chrom", "pos", "allele1", "allele2", "freq1", "meta_lnOR", "meta_z",
            "meta_p_from_z", "gene_context", "novel", "ld_index", "ld_index_type", "maf", "n_buddies",
            "start_r50", "end_r50", "start_r60", "end_r60", "start_r80", "end_r80", "n_genes_r50", "n_genes_r60",
            "n_genes_r80", "nearest_gene_symbol", "nearest_dist"]].copy()
s1["genes_r60"] = s1.locus_no.map(reg_genes)
s1 = s1.merge(ot[["locus_no", "n_credible_sets", "studies", "l2g_gene", "l2g_score", "l2g_genes_ge05",
                  "qtl_coloc_genes", "qtl_coloc_genes_clpp001", "l2g_gene_is_mendelian"]], on="locus_no", how="left")
s1 = s1.rename(columns={"qtl_coloc_genes": "qtl_coloc_genes_clpp_ge_0.1",
                        "qtl_coloc_genes_clpp001": "qtl_coloc_genes_clpp_ge_0.01"})
s1 = s1.rename(columns={"meta_p_from_z": "meta_p_corrected (from Z)", "n_buddies": "n_LD_buddies_r2_0.5"})
write("Supplementary_Table_S1_chronotype_loci.xlsx", "Supplementary Table S1 - Chronotype loci, LD intervals and gene mapping",
      [("Loci", s1, "351 lead variants (Jones et al. 2019, Supplementary Data 1) with the LD-reference index variant, "
                    "LD intervals at r2 >= 0.5/0.6/0.8 (1000 Genomes phase 3 EUR, MAF >= 1%, +/-1 Mb), protein-coding "
                    "genes in the r2 >= 0.6 interval (+10 kb), nearest gene, and Open Targets Platform 26.09 credible "
                    "sets, locus-to-gene (L2G) prioritisation and molecular-QTL colocalisations (Open Targets COLOC_PIP_ECAVIAR; "
                    "genes with eCAVIAR CLPP >= 0.1 and >= 0.01 listed separately).")],
      common_note)

# ---------------------------------------------------------------- S2 gene sets
summ = pd.read_csv(INTERIM / "genesets" / "geneset_summary.tsv", sep="\t")
gs = pd.read_csv(INTERIM / "genesets" / "genesets.tsv", sep="\t")
uni = pd.read_csv(INTERIM / "genesets" / "gene_universe.tsv", sep="\t").set_index("gene_id").symbol
gs["symbol"] = gs.gene_id.map(uni)
links = pd.read_csv(INTERIM / "genesets" / "gene_disease_links.tsv", sep="\t")
prov = json.load(open(INTERIM / "genesets" / "provenance.json"))
write("Supplementary_Table_S2_gene_sets.xlsx", "Supplementary Table S2 - Gene universe and gene sets",
      [("Gene set summary", summ, "Definition, family and size of every gene set tested."),
       ("Gene set members", gs[["set_id", "family", "label", "gene_id", "symbol"]], "Members of each gene set."),
       ("Gene-disease links", links, "Gene-disease pairs used: OMIM (Mendelian, via HPO genes_to_disease / "
                                     "mim2gene_medgen), Orphanet (disease-causing, assessed) and ClinGen "
                                     "(moderate, strong or definitive).")],
      common_note + [f"HPO release: {prov['hpo_version']}; protein-coding universe: {prov['n_universe']} genes."])

# ---------------------------------------------------------------- S3 enrichment
E = pd.read_csv(TABLES / "enrichment_all.tsv", sep="\t")
Rr = pd.read_csv(TABLES / "enrichment_relative.tsv", sep="\t")
M = pd.read_csv(TABLES / "magma_genesets.tsv", sep="\t")
hits = pd.read_csv(TABLES / "locus_set_hits.tsv", sep="\t")
write("Supplementary_Table_S3_enrichment.xlsx", "Supplementary Table S3 - Locus-level and gene-level enrichment results",
      [("Locus-level enrichment", E, "Observed loci containing >= 1 gene of each set vs matched null loci "
                                    "(10,000 permutations; exact Poisson-binomial p-values) for each analysis: primary "
                                    "(r2 >= 0.6), r2 >= 0.5, r2 >= 0.8, MHC/17q21.31 excluded, and nearest gene. "
                                    "Null loci are matched on MAF, LD partners, gene count and distance to the nearest "
                                    "gene. fold_analytic = observed / expected (exact) loci; q = Benjamini-Hochberg "
                                    "within set family. frac_of_mendelian_obs / _exp and p_relative: among loci "
                                    "containing a Mendelian gene, the fraction that also contain a gene of the set, "
                                    "observed vs matched null (same draws)."),
       ("Relative contrasts", Rr, "Pre-specified contrasts: among loci containing a gene of the reference set "
                                  "(denominator), the fraction that also contain a gene of the phenotype set "
                                  "(numerator; obs_both = loci containing a gene of both), observed vs the same "
                                  "fraction in the matched null loci (same 10,000 draws)."),
       ("MAGMA gene-set", M, "MAGMA v1.10 competitive gene-set analysis on UK Biobank chronotype (GCST007576): "
                             "marginal and conditioned on neurodevelopmental genes (cond_NDD) or Mendelian genes "
                             "(cond_MEND)."),
       ("MAGMA monoamine LOO", pd.read_csv(TABLES / "magma_monoamine_leave_one_out.tsv", sep="\t"),
        "Post hoc monoamine set: MAGMA marginal gene-set analysis leaving out each of the four genes in "
        "chronotype loci in turn."),
       ("Locus x set hits", hits, "For the primary analysis, which genes in which locus contribute to each set.")],
      common_note)

# ---------------------------------------------------------------- S4 rare variants
conv = pd.read_csv(TABLES / "burden_convergence.tsv", sep="\t")
bg = pd.read_csv(TABLES / "burden_gene_level.tsv", sep="\t")
bg = bg[bg.in_locus | (bg.p_burden < 1e-3)]
write("Supplementary_Table_S4_rare_variant_burden.xlsx",
      "Supplementary Table S4 - Exome burden evidence for chronotype at GWAS-locus genes",
      [("Convergence tests", conv, "Mean -log10 p and number of genes with burden p < 0.01 in each gene group vs "
                                   "10,000 random gene sets matched on cumulative allele frequency (CAF) decile. "
                                   "Trimmed: the three most significant genes (trimmed_genes) removed from the group "
                                   "and from every matched set. l3o (leave-three-out): the remaining genes vs untrimmed "
                                   "matched sets of the same size. Permutation p-values have a floor of 1/10,001."),
       ("Gene-level burden", bg, "ACAT-combined burden p-values across masks (M1 pLOF, M3 pLOF + deleterious "
                                 "missense; five frequency ceilings) and the four chronotype categories (UKB field "
                                 "1180; GCST90081559-62; European-ancestry exomes, n = 388,330). "
                                 "p_burden_maf_le_0.1pct drops the masks with the 1% frequency ceiling; pLOF_best_* = "
                                 "best pLOF-only mask. Genes in chronotype loci or with p < 0.001.")],
      common_note)

# ---------------------------------------------------------------- S5 catalogue
cat = pd.read_csv(TABLES / "chronomic_gene_catalogue.tsv", sep="\t")
write("Supplementary_Table_S5_chronomic_gene_catalogue.xlsx",
      "Supplementary Table S5 - Mendelian disease genes at chronotype loci (chronomic candidate genes)",
      [("Catalogue", cat, "One row per Mendelian disease gene in a chronotype locus (r2 >= 0.6 interval): diseases, "
                          "inheritance, ClinGen class, HPO phenotype flags, nearest gene and Open Targets L2G status, "
                          "MAGMA gene p, exome burden p and direction (Backman et al. 2021), QTL colocalisation tissues, "
                          "gnomAD v2.1.1 LoF constraint (LOEUF_v2; descriptive only), mouse circadian atlas and GTEx "
                          "day-night expression. evidence_count = "
                          "number of five gene-level evidence lines, which are not independent: L2G >= 0.5 for the gene "
                          "in a credible set at the locus (ev_l2g; l2g_gene_score = the gene's highest L2G score at the "
                          "locus; l2g_gene/l2g_score = the top L2G gene at the locus), nearest gene to the lead (ev_nearest), MAGMA "
                          "Bonferroni (ev_magma), exome burden p < 0.01 (ev_burden), QTL colocalisation with eCAVIAR "
                          "CLPP >= 0.1 (ev_qtl; qtl_max_clpp gives the largest CLPP >= 0.01).")],
      common_note)

# ---------------------------------------------------------------- S6 coloc + provenance
man = pd.read_csv(ROOT / "data" / "manifest.tsv", sep="\t")
write("Supplementary_Table_S6_colocalisation_and_provenance.xlsx",
      "Supplementary Table S6 - KCNH2 colocalisation and data provenance",
      [("KCNH2 coloc", pd.read_csv(TABLES / "coloc_kcnh2.tsv", sep="\t"),
        "Unconditional coloc ABF of UK Biobank chronotype (GCST007576) and QT interval (Hoffmann et al. 2022, "
        "GCST90165291) around rs2072413 (priors p1 = p2 = 1e-4, p12 = 5e-6)."),
       ("KCNH2 coloc SNPs", pd.read_csv(TABLES / "coloc_kcnh2_snps.tsv", sep="\t"),
        "Top variants by posterior probability of being the shared variant (unconditional, +/-250 kb window)."),
       ("KCNH2 LD", pd.read_csv(TABLES / "coloc_kcnh2_ld.tsv", sep="\t"),
        "LD (r2, 1000G EUR) between the chronotype lead, the top chronotype variant and the top QT variant."),
       ("Conditional coloc", pd.read_csv(TABLES / "coloc_kcnh2_conditional.tsv", sep="\t"),
        "Coloc of chronotype with the QT signal tagging the chronotype lead after conditioning the QT statistics "
        "on other independent QT signals (approximate conditional analysis with signed 1000G EUR LD; variants "
        "with QT n >= 95% of the maximum). Grid: window +/-100 or 250 kb; LD ridge 0.001, 0.01 or 0.05; "
        "conditioning on all other signals, on the top QT signal only, or on all but the weakest; p12 5e-6 or 1e-5."),
       ("Conditional signals", pd.read_csv(TABLES / "coloc_kcnh2_conditional_signals.tsv", sep="\t"),
        "Each independent QT signal from stepwise selection (conditional p < 5e-8), conditioned on the others, "
        "and its colocalisation with chronotype."),
       ("Conditional SNPs", pd.read_csv(TABLES / "coloc_kcnh2_conditional_snps.tsv", sep="\t"),
        "Variant-level z-scores (chronotype; QT marginal; QT conditioned on the other signals or on the top signal "
        "only) for the +/-250 kb window (ridge 0.001)."),
       ("Data manifest", man, "Every input: URL (or API endpoint), retrieval time (UTC), size and MD5 checksum.")],
      common_note)
print("written:", sorted(p.name for p in OUT.glob("*.xlsx")))
